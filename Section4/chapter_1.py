# Conditionals

tea_leaves = 20

if(tea_leaves > 10):
    print("You have enough tea leaves to make a cup of tea")
else:
    print("You do not have enough tea leaves to make a cup of tea")

kettle_boiled = False

if kettle_boiled:
    print("Kettle is Boiled, You can make tea")
else:
    print("Kettle is not Boiled, You cannot make tea")